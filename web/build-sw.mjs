// Writes sw.js with every file of the web build and a fresh cache name: node build-sw.mjs
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
// the 3D explorers (a few MB) are not pre-cached: each loads when needed and then stays in its own cache (see below)
const skip = new Set(['sw.js', 'build-sw.mjs', 'test', 'netlify.toml', '_headers', 'package.json', 'explorers']);
const files = [];
const walk = d => { for (const n of readdirSync(d || '.')) { if (skip.has(n) || n.startsWith('.')) continue; const p = d ? d + '/' + n : n; statSync(p).isDirectory() ? walk(p) : files.push(p); } };
process.chdir(new URL('.', import.meta.url).pathname); walk('');
const h = createHash('sha1'); for (const f of files.sort()) h.update(f).update(readFileSync(f));
const cache = 'kiki-safari-' + h.digest('hex').slice(0, 10);
writeFileSync('sw.js', `// Generated by build-sw.mjs. Offline cache: after the first visit the game opens with no signal; files refresh in the background.
const CACHE = '${cache}';\nconst MODELS = 'kiki-models-2'; // bump when the explorer models change
const FILES = ${JSON.stringify(['./', ...files], null, 2)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(k => Promise.all(k.filter(x => (x.startsWith('kiki-safari-') && x !== CACHE) || (x.startsWith('kiki-models-') && x !== MODELS)).map(x => caches.delete(x)))).then(() => self.clients.claim())); });
// Notifications (Phase 4): gifts, friend requests and Portal Surge reminders from the push server.
self.addEventListener('push', e => {
  let d = {}; try { d = e.data ? e.data.json() : {}; } catch (x) {}
  e.waitUntil(self.registration.showNotification(d.title || 'KIKI SAFARI', { body: d.body || '', icon: 'assets/icons/icon-192.png', badge: 'assets/icons/icon-192.png', data: { url: d.url || './' } }));
});
self.addEventListener('notificationclick', e => {
  e.notification.close();
  e.waitUntil(self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then(list => list.length ? list[0].focus() : self.clients.openWindow(e.notification.data.url || './')));
});
self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return; // map data is cached by the game itself
  if (url.pathname.includes('/assets/explorers/')) { // 3D explorer models: from their own cache, which survives updates
    e.respondWith(caches.open(MODELS).then(c => c.match(e.request).then(hit => hit || fetch(e.request).then(res => { if (res.ok) c.put(e.request, res.clone()); return res; }))));
    return;
  }
  e.respondWith(caches.open(CACHE).then(cache => cache.match(e.request, { ignoreSearch: true }).then(hit => {
    const fresh = fetch(e.request).then(res => { if (res.ok) cache.put(e.request, res.clone()); return res; }).catch(() => hit);
    return hit || fresh;
  })));
});
`);
console.log(cache, files.length, 'files');
